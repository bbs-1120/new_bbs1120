function parsePrice(priceStr) {
  if (!priceStr) return 0;
  // ¥9,000 → 9000
  return parseInt(priceStr.replace(/[¥,]/g, ""), 10) || 0;
}

function parseData(data) {
  const lines = data.split("\n").filter(l => l.trim());
  const prices = [];

  for (const line of lines) {
    const parts = line.split("\t");
    if (parts.length < 3) continue;

    const offerKey = parts[0].trim();
    const yesterdayPrice = parsePrice(parts[1]);
    const todayPrice = parsePrice(parts[2]);

    if (!offerKey) continue;

    // オファーキーをパース: 案件名_オファー名_媒体名
    const keyParts = offerKey.split("_");
    if (keyParts.length < 3) continue;

    const media = keyParts[keyParts.length - 1];
    const projectName = keyParts[0];
    const offerName = keyParts.slice(1, -1).join("_");

    prices.push({
      offerKey,
      projectName,
      offerName,
      media,
      yesterdayPrice,
      todayPrice,
    });
  }

  return prices;
}

